class BuiltInMath {
    public static void main(String[] args) {
        double num = 25;
        double squareRoot = Math.sqrt(num);
        double power = Math.pow(num, 2);
        System.out.println("Number = " + num);
        System.out.println("Square Root = " + squareRoot);
        System.out.println("Power = " + power);
    }
}
